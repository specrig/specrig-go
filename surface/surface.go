package surface

import (
	"bytes"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"gopkg.in/yaml.v3"
)

// Format is what this package writes under specrig: and the newest it reads.
const Format = "surface/1"

// File is where a service keeps its record, from the module root.
var File = filepath.Join("tests", "surface.yaml")

// ErrForeign is a file at a record's path that does not say it is one.
var ErrForeign = errors.New("not a specrig record")

// Identify checks that body says it is a record of format, as an OpenAPI
// document says so under openapi:.
func Identify(body []byte, format string) error {
	// A file that does not parse is more likely ours mid-merge than somebody else's.
	var doc yaml.Node
	if err := yaml.Unmarshal(body, &doc); err != nil {
		return err
	}
	var head struct {
		Specrig string `yaml:"specrig"`
	}
	if doc.Decode(&head) != nil || head.Specrig == "" {
		return ErrForeign
	}
	kind, newest := split(format)
	gotKind, got := split(head.Specrig)
	switch {
	case gotKind != kind || got < 1:
		return fmt.Errorf("specrig: %s is not a %s record", head.Specrig, kind)
	case got > newest:
		return fmt.Errorf("specrig: %s is newer than this specrig-go reads (%s)", head.Specrig, format)
	}
	return nil
}

func split(format string) (string, int) {
	kind, version, _ := strings.Cut(format, "/")
	n, _ := strconv.Atoi(version)
	return kind, n
}

type Surface struct {
	Specrig   string              `yaml:"specrig"`
	Service   string              `yaml:"service"`
	Publishes []string            `yaml:"publishes,omitempty"`
	Consumes  []string            `yaml:"consumes,omitempty"`
	Serves    []string            `yaml:"serves,omitempty"`
	Calls     []string            `yaml:"calls,omitempty"`
	Clients   map[string][]string `yaml:"clients,omitempty"`
	// Calls between the module's own domains: a modular monolith's links.
	Domains []string `yaml:"domains,omitempty"`
	// From the service's specrig.yaml, not its code.
	Hosts map[string]string `yaml:"-"`
}

const header = "# Generated by `go tool specrig surface` from the module's code.\n"

func (s Surface) Encode() []byte {
	var b bytes.Buffer
	b.WriteString(header)
	enc := yaml.NewEncoder(&b)
	enc.SetIndent(2)
	_ = enc.Encode(s)
	return b.Bytes()
}

func Read(file string) (Surface, error) {
	body, err := os.ReadFile(file)
	if err != nil {
		return Surface{}, err
	}
	if err := Identify(body, Format); err != nil {
		return Surface{}, fmt.Errorf("%s: %w", file, err)
	}
	var s Surface
	if err := yaml.Unmarshal(body, &s); err != nil {
		return Surface{}, fmt.Errorf("%s: %w", file, err)
	}
	if s.Service == "" {
		return Surface{}, fmt.Errorf("%s: no service", file)
	}
	return s, nil
}
