package replacements

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

const container = `// Code generated by diogen. DO NOT EDIT.

package diogen

import (
	sql "example.test/pkg/sql"
)

type Replacements struct {
	SqlDb sql.Db
}

type Application struct{}

func InitAppWith(Replacements) (*Application, error) { return &Application{}, nil }
`

const sqlPkg = `package sql

type Db interface{ Ping() }
`

// The denial comes from there being no specrig.yaml at all: an absent list grants
// nothing.
const violating = `package feature

import "example.test/config/diogen"

func boot() {
	_, _ = diogen.InitAppWith(diogen.Replacements{SqlDb: nil})
}
`

// GOWORK off, because the fixture sits outside any workspace this repository has.
func module(t *testing.T) {
	t.Helper()
	t.Setenv("GOWORK", "off")
	t.Chdir(t.TempDir())

	files := map[string]string{
		"go.mod": "module example.test\n\ngo 1.27\n",
		"config/di/di.go": "//go:generate diogen -output config/diogen/di_gen.go $GOFILE\n\n" +
			"package di\n",
		"config/diogen/di_gen.go":     container,
		"pkg/sql/sql.go":              sqlPkg,
		"tests/feature/steps_test.go": violating,
	}
	for name, body := range files {
		path := filepath.FromSlash(name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

// The bare command used to be the one that failed, so the report must not keep
// failing on what it is only reporting.
func TestBareRunReportsAndDoesNotRefuse(t *testing.T) {
	module(t)

	if err := New().Run(t.Context()); err != nil {
		t.Fatalf("bare run: %v", err)
	}
}

func TestCheckRefusesAnUngrantedSeam(t *testing.T) {
	module(t)

	err := New().Run(t.Context(), "check")

	if err == nil {
		t.Fatal("check passed a seam nothing grants")
	}
	if !strings.Contains(err.Error(), "SqlDb") {
		t.Fatalf("the refusal does not name the field: %v", err)
	}
}

func TestCheckPassesWhenTheListGrantsIt(t *testing.T) {
	module(t)
	yaml := "replacements:\n  allow:\n    example.test/pkg/sql: [Db]\n"
	if err := os.WriteFile("specrig.yaml", []byte(yaml), 0o644); err != nil {
		t.Fatal(err)
	}

	if err := New().Run(t.Context(), "check"); err != nil {
		t.Fatalf("check refused a granted field: %v", err)
	}
}

func TestUnknownSubcommandIsRefused(t *testing.T) {
	module(t)

	err := New().Run(t.Context(), "suggest")

	if err == nil || !strings.Contains(err.Error(), "suggest") {
		t.Fatalf("run: %v", err)
	}
}
